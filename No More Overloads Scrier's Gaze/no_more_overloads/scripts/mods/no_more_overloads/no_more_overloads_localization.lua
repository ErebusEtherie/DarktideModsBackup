-- Resolve an official game term in the player's language, falling back to our own wording.
-- Localize never returns nil: an unknown key yields "<unlocalized ...>", the manager returns
-- "" until its string bundles are ready, and the global itself is false before it exists.
local function game_term(key, fallback)
	if not Localize then
		return fallback
	end
	local text = Localize(key)
	if not text or text == "" or string.sub(text, 1, 1) == "<" then
		return fallback
	end
	return text
end

