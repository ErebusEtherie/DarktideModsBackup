-- Every tooltip ends with the widget's default, e.g. "... (Default = On)". `default` is one
-- display string for all languages, or a table keyed by language. `translations` may be empty
-- for settings whose tooltip is only the default.
local function with_default(default, translations)
	local out = {}
	for i = 1, #LANGUAGES do
		local lang = LANGUAGES[i]
		local value = type(default) == "table" and (default[lang] or default.en) or default
		local suffix = string.format("(%s = %s)", WORD_DEFAULT[lang] or WORD_DEFAULT.en, value)
		local text = translations[lang]
		out[lang] = text and (text .. " " .. suffix) or suffix
	end
	return out
end

